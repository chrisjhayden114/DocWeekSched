/**
 * Regenerates lib/featureGuideAuto.ts from the PNGs in
 * public/feature-guide/auto/ so the browser bundle knows which CI screenshots
 * actually exist. Run from apps/web (`npm run gen:auto-shots`).
 *
 * WHY a generated module: the shared featureGuide entries only carry the
 * founder's manual shots. The auto directory is filled in by
 * .github/workflows/screenshots.yml, and a component cannot stat a file at
 * render time — so the directory listing is compiled in instead. The workflow
 * runs this immediately after capture and commits the result alongside the
 * images; `__tests__/featureGuideAuto.test.ts` fails if the two drift.
 */

import { existsSync, readdirSync, writeFileSync } from "fs";
import { join } from "path";

const AUTO_DIR = join(process.cwd(), "public/feature-guide/auto");
const OUT = join(process.cwd(), "lib/featureGuideAuto.ts");

const HEADER = `/**
 * GENERATED by scripts/gen-feature-guide-auto.mjs — do not edit by hand.
 *
 * Feature keys with a CI-captured screenshot committed under
 * public/feature-guide/auto/. Run \`npm run gen:auto-shots\` after changing
 * that directory; a test asserts this list matches it.
 */

import type { FeatureKey } from "@event-app/shared";

export const FEATURE_GUIDE_AUTO_KEYS: FeatureKey[] = [
`;

const keys = existsSync(AUTO_DIR)
  ? readdirSync(AUTO_DIR)
      .filter((f) => f.endsWith(".png"))
      .map((f) => f.replace(/\.png$/, ""))
      .sort()
  : [];

const body = keys.map((key) => `  ${JSON.stringify(key)},\n`).join("");

writeFileSync(OUT, `${HEADER}${body}];\n`, "utf8");
console.log(`Wrote ${keys.length} auto screenshot keys to lib/featureGuideAuto.ts`);
